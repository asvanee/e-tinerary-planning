import { getTripDateRangeError } from "../tripDateRange";

describe("getTripDateRangeError", () => {
  test.each([
    ["วันเดียว", "2026-11-13", "2026-11-13"],
    ["31 วันพอดี", "2026-11-13", "2026-12-13"],
    ["ข้ามปี", "2026-12-20", "2027-01-05"],
    ["ข้าม 29 ก.พ.", "2028-02-20", "2028-03-01"],
  ])("%s → ผ่าน", (_label, start, end) => {
    expect(getTripDateRangeError(start, end)).toBeNull();
  });

  test("32 วัน → ไม่ผ่าน", () => {
    expect(getTripDateRangeError("2026-11-13", "2026-12-14")).toBe("ทริปยาวได้ไม่เกิน 31 วัน");
  });

  test("วันจบก่อนวันเริ่ม → ไม่ผ่าน", () => {
    expect(getTripDateRangeError("2026-11-13", "2026-11-12")).toBe(
      "วันที่สิ้นสุดต้องไม่ก่อนวันที่เริ่มต้น"
    );
  });

  test.each([
    ["รูปแบบอื่น", "13/11/2026", "2026-11-14"],
    ["ไม่มีวันนั้นจริง", "2026-02-30", "2026-03-02"],
    ["มีเวลาต่อท้าย", "2026-11-13", "2026-11-14T00:00:00Z"],
    ["ไม่ใช่ string", 20261113, "2026-11-14"],
  ])("%s → รูปแบบวันที่ไม่ถูกต้อง", (_label, start, end) => {
    expect(getTripDateRangeError(start, end)).toBe("รูปแบบวันที่ไม่ถูกต้อง");
  });
});
